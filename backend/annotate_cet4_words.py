def strip_punctuation(word: str) -> str:
    """去除单词首尾的标点"""
    return re.sub(r'^[^\w\'-]+|[^\w\'-]+$', '', word)


def grammar_has_chinese(grammar: list) -> bool:
    """检查 grammar 数组是否已有逐词中文"""
    for item in grammar:
        if isinstance(item, dict) and item.get("chinese"):
            return True
    return False


def build_lesson_vocab(statements: list) -> dict[str, str]:
    """从本课单词语义条目建立 word→chinese 词典"""
    vocab = {}
    for s in statements:
        eng = s.get("english", "").strip()
        cn = s.get("chinese", "").strip()
        words = [strip_punctuation(w) for w in eng.split()]
        # 只收录单词语义（1-2个词）
        if 1 <= len(words) <= 2 and cn:
            key = words[0].lower()
            if key not in vocab:
                vocab[key] = cn
            # 如果是两个词的短语，也收录每个词
            if len(words) == 2:
                w1_lower = words[0].lower()
                w2_lower = words[1].lower()
                if w1_lower not in vocab:
                    vocab[w1_lower] = cn  # 保存原短语释义，由具体匹配决定
                if w2_lower not in vocab:
                    vocab[w2_lower] = cn
    return vocab


def lookup_chinese(word: str, lesson_vocab: dict, fallback: dict) -> str | None:
    """查找单词的中文释义（带词形还原）"""
    clean = strip_punctuation(word)
    raw = word  # 保留原始形式

    # 按优先级尝试
    candidates = [
        raw, raw.lower(),
        clean, clean.lower(),
    ]

    for c in candidates:
        if c in lesson_vocab:
            return lesson_vocab[c]
        if c in fallback:
            return fallback[c]

    low_clean = clean.lower()

    # 词形还原：去掉 -s, -es, -ies, -ves, -ed, -ing, -er, -est, -ly 等
    forms_to_try = []

    # 复数/第三人称
    if low_clean.endswith("ies") and len(low_clean) > 4:
        forms_to_try.append(low_clean[:-3] + "y")  # studies → study
    if low_clean.endswith("ves") and len(low_clean) > 4:
        forms_to_try.append(low_clean[:-3] + "f")  # wives → wife
        forms_to_try.append(low_clean[:-3] + "fe")  # lives → life
    if low_clean.endswith("ses") and len(low_clean) > 4:
        forms_to_try.append(low_clean[:-2])  # classes → class
    if low_clean.endswith("xes") and len(low_clean) > 4:
        forms_to_try.append(low_clean[:-2])  # boxes → box
    if low_clean.endswith("s") and not low_clean.endswith("ss") and len(low_clean) > 2:
        forms_to_try.append(low_clean[:-1])  # notes → note, words → word

    # 过去式/-ing 形式
    if low_clean.endswith("ing"):
        base = low_clean[:-3]
        forms_to_try.append(base)  # reading → read
        forms_to_try.append(base + "e")  # taking → take, reading → reade(no)
        # 双写辅音: running → run, getting → get
        if len(base) >= 3 and base[-1] == base[-2] and base[-1] not in "aeiou":
            forms_to_try.append(base[:-1])
    if low_clean.endswith("ed"):
        base = low_clean[:-2]
        forms_to_try.append(base)  # worked → work
        forms_to_try.append(base[:-1])  # stopped → stop
        forms_to_try.append(base + "e")  # liked → like
    if low_clean.endswith("er") and len(low_clean) > 3:
        forms_to_try.append(low_clean[:-2])  # better → bett(no), bigger → bigg → big
        forms_to_try.append(low_clean[:-1])  # teacher → teache(no)
    if low_clean.endswith("est") and len(low_clean) > 4:
        forms_to_try.append(low_clean[:-3])  # biggest → bigg
        forms_to_try.append(low_clean[:-4])  # largest → larg → large
    if low_clean.endswith("ly") and len(low_clean) > 3:
        forms_to_try.append(low_clean[:-2])  # carefully → careful

    for f in forms_to_try:
        if f in lesson_vocab:
            return lesson_vocab[f]
        if f in fallback:
            return fallback[f]

    # 比较级/最高级特殊词
    irregular_forms = {
        "better": "good", "best": "good",
        "worse": "bad", "worst": "bad",
        "more": "much", "most": "much",
        "less": "little", "least": "little",
        "bigger": "big", "biggest": "big",
        "larger": "large", "largest": "large",
        "smaller": "small", "smallest": "small",
        "higher": "high", "highest": "high",
        "lower": "low", "lowest": "low",
    }
    if low_clean in irregular_forms:
        base = irregular_forms[low_clean]
        if base in lesson_vocab:
            return lesson_vocab[base]
        if base in fallback:
            return fallback[base]

    return None


def process_file(filepath: Path) -> int:
    with open(filepath, "r", encoding="utf-8") as f:
        statements = json.load(f)

    # 建立本课单词语义词典
    lesson_vocab = build_lesson_vocab(statements)

    modified = 0

    for stmt in statements:
        english = stmt.get("english", "")
        grammar = stmt.get("grammar")

        if not isinstance(grammar, list) or len(grammar) == 0:
            continue

        first = grammar[0]
        # 判断是否是 label 格式（原始 CET-4 格式）
        is_label_format = "label" in first and not grammar_has_chinese(grammar)
        # 判断是否已经是逐词格式但有空缺
        is_incomplete = (
            "text" in first
            and any(
                isinstance(item, dict)
                and not item.get("chinese")
                and not item.get("role")
                and item.get("text")
                and item["text"].strip(".?!,;:'\"()[]{}-—")
                for item in grammar
            )
        )

        if not is_label_format and not is_incomplete:
            continue

        words = english.split()
        if len(words) <= 1:
            continue

        # 多词句子：生成逐词 grammar 带中文
        new_grammar = []
        for word in words:
            cn = lookup_chinese(word, lesson_vocab, BUILTIN_DICT)
            item = {"text": word}
            if cn:
                item["chinese"] = cn
            new_grammar.append(item)

        stmt["grammar"] = new_grammar
        modified += 1

    if modified > 0:
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(statements, f, ensure_ascii=False, indent=2)
        print(f"  ✓ {filepath.name}: {modified} 句已补充逐词中文")

    return modified


def main():
    files = sorted(DATA_DIR.glob("*.json"))
    total = 0
    for fp in files:
        n = process_file(fp)
        total += n
    print(f"\n总计: {total} 句已更新逐词中文释义")


if __name__ == "__main__":
    main()

# Merge phrase dict into word dict
for k, v in PHRASE_DICT.items():
    WORD_DICT[k] = v


def get_word_chinese(word: str) -> str:
    """获取单词或短语的中文释义"""
    # 1. 精确匹配
    if word in WORD_DICT:
        return WORD_DICT[word]

    # 2. 大小写不敏感匹配
    lower = word.lower()
    if lower in WORD_DICT:
        return WORD_DICT[lower]

    # 3. 去掉首尾标点后匹配
    stripped = re.sub(r'^[^\w\']+|[^\w\']+$', '', word)
    if stripped in WORD_DICT:
        return WORD_DICT[stripped]
    if stripped.lower() in WORD_DICT:
        return WORD_DICT[stripped.lower()]

    # 4. 多词短语 → 拆分后逐词翻译
    if ' ' in word:
        parts = word.split()
        chinese_parts = []
        for part in parts:
            ch = get_word_chinese(part)  # 递归翻译每个词
            if ch:
                chinese_parts.append(ch)
        if chinese_parts:
            return '/'.join(chinese_parts)
        return ""

    # 5. 去掉缩写后缀 've, 're, 'll, 'd, 'm, n't, 's
    for suffix in ["'ve", "'re", "'ll", "'d", "'m", "n't", "'s"]:
        if lower.endswith(suffix):
            base = lower[:-len(suffix)]
            if base in WORD_DICT:
                return WORD_DICT[base]
            if base + "e" in WORD_DICT:
                return WORD_DICT[base + "e"]

    # 6. 去掉复数/三单 s/es/ies
    if lower.endswith("ies"):
        base = lower[:-3] + "y"
        if base in WORD_DICT:
            return WORD_DICT[base]
    if lower.endswith("ves"):
        base = lower[:-3] + "f"
        if base in WORD_DICT:
            return WORD_DICT[base]
    if lower.endswith("es") and len(lower) > 3:
        base = lower[:-2]
        if base in WORD_DICT:
            return WORD_DICT[base]
    if lower.endswith("s") and not lower.endswith("ss") and len(lower) > 3:
        base = lower[:-1]
        if base in WORD_DICT:
            return "…们/复数(" + WORD_DICT[base] + ")"
        if base + "e" in WORD_DICT:
            return WORD_DICT[base + "e"]

    # 7. 去掉 ing/ed
    if lower.endswith("ing") and len(lower) > 5:
        base = lower[:-3]
        if base in WORD_DICT:
            return WORD_DICT[base]
        base_e = base + "e"
        if base_e in WORD_DICT:
            return "正在…(" + WORD_DICT[base_e] + ")"
        # 双写辅音+ing
        if len(base) > 1 and base[-1] == base[-2]:
            base2 = base[:-1]
            if base2 in WORD_DICT:
                return "正在…(" + WORD_DICT[base2] + ")"

    if lower.endswith("ed") and len(lower) > 4:
        base = lower[:-2]
        if base in WORD_DICT:
            return WORD_DICT[base]
        base_e = base + "e"
        if base_e in WORD_DICT:
            return WORD_DICT[base_e]
        # y → ied
        base_y = lower[:-3] + "y"
        if base_y in WORD_DICT:
            return WORD_DICT[base_y]
        # 双写辅音+ed
        if len(base) > 1 and base[-1] == base[-2]:
            base2 = base[:-1]
            if base2 in WORD_DICT:
                return WORD_DICT[base2]

    # 8. 去掉 ly
    if lower.endswith("ly") and len(lower) > 4:
        base = lower[:-2]
        if base in WORD_DICT:
            return "…地(" + WORD_DICT[base] + ")"
        base_e = base + "e"
        if base_e in WORD_DICT:
            return "…地(" + WORD_DICT[base_e] + ")"
        # y → ily
        base_y = lower[:-3] + "y"
        if base_y in WORD_DICT:
            return "…地(" + WORD_DICT[base_y] + ")"

    # 9. 去掉 er/est 比较级/最高级
    if lower.endswith("est") and len(lower) > 4:
        base = lower[:-3]
        if base in WORD_DICT:
            return "最…的(" + WORD_DICT[base] + ")"
        base_e = base + "e"
        if base_e in WORD_DICT:
            return "最…的(" + WORD_DICT[base_e] + ")"
        if len(base) > 1 and base[-1] == base[-2]:
            base2 = base[:-1]
            if base2 in WORD_DICT:
                return "最…的(" + WORD_DICT[base2] + ")"

    if lower.endswith("er") and len(lower) > 3:
        base = lower[:-2]
        if base in WORD_DICT:
            return "更…的/…者(" + WORD_DICT[base] + ")"
        base_e = base + "e"
        if base_e in WORD_DICT:
            return "更…的/…者(" + WORD_DICT[base_e] + ")"
        if len(base) > 1 and base[-1] == base[-2]:
            base2 = base[:-1]
            if base2 in WORD_DICT:
                return "更…的/…者(" + WORD_DICT[base2] + ")"

    # 返回空
    return ""


def process_statement(statement: dict) -> bool:
    """处理单个 statement，为 grammar 添加 chinese 字段。返回是否有修改。"""
    grammar = statement.get("grammar")
    if not grammar or not isinstance(grammar, list):
        return False

    modified = False
    for item in grammar:
        if not isinstance(item, dict):
            continue
        if "chinese" in item and item["chinese"]:
            continue

        text = item.get("text", "")
        if text:
            ch = get_word_chinese(text)
            if ch:
                item["chinese"] = ch
                modified = True
            elif "chinese" not in item:
                item["chinese"] = ""
        elif "chinese" not in item:
            item["chinese"] = ""

    return modified


def process_file(filepath: str) -> int:
    """处理单个 JSON 文件，返回修改的 statement 数量。"""
    with open(filepath, "r", encoding="utf-8") as f:
        statements = json.load(f)

    modified_count = 0
    for stmt in statements:
        if process_statement(stmt):
            modified_count += 1

    if modified_count > 0:
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(statements, f, ensure_ascii=False, indent=2)
        rel_path = "/".join(filepath.rsplit("/", 2)[-2:])
        print(f"  ✓ {rel_path}: {modified_count} statements updated")

    return modified_count


def main():
    base_dir = os.path.join(os.path.dirname(__file__), "app", "data", "earthworm")
    if not os.path.isdir(base_dir):
        print(f"Error: directory not found: {base_dir}")
        return

    json_files = sorted(glob.glob(os.path.join(base_dir, "**/*.json"), recursive=True))
    print(f"Found {len(json_files)} JSON files\n")

    total_modified = 0
    for filepath in json_files:
        count = process_file(filepath)
        total_modified += count

    # 统计
    all_grammar_words = 0
    all_with_chinese = 0
    for filepath in json_files:
        with open(filepath, "r", encoding="utf-8") as f:
            statements = json.load(f)
        for stmt in statements:
            grammar = stmt.get("grammar")
            if grammar:
                for item in grammar:
                    if isinstance(item, dict) and item.get("text"):
                        all_grammar_words += 1
                        if item.get("chinese"):
                            all_with_chinese += 1

    pct = 100 * all_with_chinese // max(all_grammar_words, 1)
    print(f"\n{'='*50}")
    print(f"Total files processed: {len(json_files)}")
    print(f"Total statements with grammar modified: {total_modified}")
    print(f"Total grammar words: {all_grammar_words}")
    print(f"Words with Chinese: {all_with_chinese} ({pct}%)")
    print(f"Words without Chinese: {all_grammar_words - all_with_chinese}")
    print(f"\nDone! All JSON files updated.")


if __name__ == "__main__":
    main()
